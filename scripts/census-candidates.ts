// Census candidate scan: streams the corpus dump, ranks clone-side reminds
// votes by net (pure module from src/curation), and writes the candidate
// file for hand-curation. This script PROPOSES ONLY: the output is a ranked
// list, and nothing reaches Fragrance.inspiredById until
// loadApprovedCloneEdges runs with the curator's approved file.

import { createReadStream } from "node:fs";
import { createWriteStream } from "node:fs";
import { createInterface } from "node:readline";
import { houseSlugFor, rankCloneCandidates, type CorpusRowInput } from "../src/curation/censusCandidates";

// the same seven houses the feed already tiers as clone houses (catalog.ts);
// duplicating the literal here keeps the scan offline (no DB access)
const CLONE_TIER_HOUSE_SLUGS = new Set([
  "afnan",
  "arabiyat-prestige",
  "armaf",
  "lattafa-perfumes",
  "paris-corner",
  "fragrance-world",
  "mykonos",
]);

function parseArgs(): { file: string; out: string } {
  const args = process.argv.slice(2);
  const flag = (name: string): string | undefined => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const file = flag("--file");
  const out = flag("--out");
  if (!file || !out) {
    console.error("usage: tsx scripts/census-candidates.ts --file <perfumes.jsonl> --out <candidates.json>");
    process.exit(2);
  }
  return { file, out };
}

async function main(): Promise<void> {
  const { file, out } = parseArgs();
  const rows: CorpusRowInput[] = [];
  const stream = createReadStream(file, "utf8");
  const reader = createInterface({ input: stream, crlfDelay: Infinity });
  let seen = 0;
  for await (const line of reader) {
    if (line.trim() === "") continue;
    const r = JSON.parse(line) as Record<string, unknown>;
    seen += 1;
    const similar = r.similar as { reminds_me_of?: unknown[] } | undefined;
    const reminds = (similar?.reminds_me_of ?? []) as Array<Record<string, unknown>>;
    if (reminds.length === 0) continue;
    // only clone-house rows have their reminds lists read as a clone side
    if (!CLONE_TIER_HOUSE_SLUGS.has(houseSlugFor(String(r.brand)))) continue;

    rows.push({
      fid: Number(r.id),
      slug: String(r.slug),
      brand: String(r.brand),
      name: String(r.name),
      reminds: reminds.map((e) => ({
        targetFid: Number(e.id),
        targetBrand: String(e.slug).split("/")[0]?.replace(/-/g, " ") ?? "",
        targetName: String(e.slug).split("/")[1]?.replace(/-/g, " ") ?? "",
        up: Number(e.up_votes ?? 0),
        down: Number(e.down_votes ?? 0),
      })),
    });
  }

  const candidates = rankCloneCandidates(rows, { cloneHouseSlugs: CLONE_TIER_HOUSE_SLUGS });
  // committed artifact keeps only what a curator can trawl: strong consensus
  // plus MEANINGFUL dissent (the community's loud no, like Khamrah vs
  // Angels' Share), not the 3.7k noise edges every stock comparison carries
  const strong = candidates.filter((c) => !c.disputed);
  const notableDisputes = candidates
    .filter((c) => c.disputed && c.down >= 500)
    .sort((a, b) => b.up - a.up);
  const curated = [...strong, ...notableDisputes];  const header =
    `// GENERATED by scripts/census-candidates.ts against the corpus dump.\n` +
    `// Signal provenance: Fragrantica community reminds_me_of up/down votes,\n` +
    `// point-in-time snapshot. Ranked by net votes. disputed=net<0 marks\n` +
    `// folklore disagreements the community itself casts. PROPOSALS ONLY:\n` +
    `// nothing enters the census until a curator approves the pair in\n` +
    `// curation/clone-edges.approved.json and the loader runs.\n`;
  const body = JSON.stringify(curated, null, 2);
  const writer = createWriteStream(out, "utf8");
  writer.write(header + "export const CENSUS_CANDIDATES = " + body + "; /* eslint-disable */\n");
  writer.end();

  const concise = (c: (typeof curated)[number]) => `${c.cloneBrand} ${c.cloneName} -> ${c.targetName} (${c.up}/${c.down})`;
  console.log(`scanned ${seen} corpus rows`);
  console.log(`clone-side rows with reminds signal: ${rows.length}`);
  console.log(`strong (net>=100): ${strong.length}`);
  console.log(`notable disputes (down>=500): ${notableDisputes.length}`);
  console.log("sample strong:", curated.filter((c) => !c.disputed).slice(0, 5).map(concise));
  console.log("sample disputes:", notableDisputes.slice(0, 3).map(concise));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
